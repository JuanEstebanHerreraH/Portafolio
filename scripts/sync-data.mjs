import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const data = JSON.parse(await readFile(path.join(root, 'data/content.json'), 'utf8'));
if (!Array.isArray(data.projects) || !Array.isArray(data.certifications)) {
  throw new Error('El contenido debe incluir projects y certifications.');
}
const serialized = JSON.stringify(data).replace(/</g, '\\u003c');
await writeFile(path.join(root, 'data/content.js'), '/* Generated by scripts/sync-data.mjs. */\nwindow.PORTFOLIO_DATA = ' + serialized + ';\n', 'utf8');
console.log('content.js actualizado desde content.json.');
