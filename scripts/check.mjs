import {readFile, stat} from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const errors = [];
const assert = (condition, message) => { if (!condition) errors.push(message); };
const read = relative => readFile(path.join(root, relative), 'utf8');
const exists = async relative => {
  const absolute = path.resolve(root, relative);
  if (!absolute.startsWith(root)) return false;
  try { return (await stat(absolute)).isFile(); } catch { return false; }
};
const bilingual = (value, label) => {
  assert(value && typeof value.es === 'string' && !!value.es.trim(), label + ': falta español.');
  assert(value && typeof value.en === 'string' && !!value.en.trim(), label + ': falta inglés.');
};
const https = (value, label) => {
  try { assert(new URL(value).protocol === 'https:', label + ': debe usar HTTPS.'); }
  catch { errors.push(label + ': URL inválida.'); }
};

const data = JSON.parse(await read('data/content.json'));
assert(Array.isArray(data.projects) && data.projects.length > 0, 'No hay proyectos.');
const ids = new Set();
for (const project of data.projects) {
  assert(!ids.has(project.id), 'ID duplicado: ' + project.id);
  assert(/^[A-Za-z0-9_.-]+$/.test(project.id), 'ID incompatible: ' + project.id);
  ids.add(project.id);
  for (const field of ['summary','role','problem','limits']) bilingual(project[field], project.id + '.' + field);
  for (const lang of ['es','en']) {
    assert(Array.isArray(project.contributions?.[lang]) && project.contributions[lang].length > 0, project.id + ': faltan aportes ' + lang);
  }
  assert(await exists(project.image), 'Imagen ausente: ' + project.image);
  assert(['screenshot','concept'].includes(project.imageType), 'Tipo de imagen inválido: ' + project.id);
  for (const field of ['url','demo','download']) if (project[field]) https(project[field], project.id + '.' + field);
}
for (const [i, item] of data.certifications.entries()) https(item.url, 'Certificado ' + i);
for (const item of data.education) { bilingual(item.title, 'Título'); bilingual(item.detail, 'Educación'); }
for (const relative of ['data/content.js','js/app.js','js/aurora.js']) {
  try { new vm.Script(await read(relative), {filename:relative}); }
  catch (error) { errors.push(error.message); }
}
for (const skill of data.skills) {
  for (const field of ['label','title','intro','practice','status']) bilingual(skill[field], skill.id + '.' + field);
  for (const id of skill.projects) assert(ids.has(id), 'Evidencia desconocida: ' + id);
}
for (const name of ['CV-Juan-Esteban-Desarrollo.pdf','CV-Juan-Esteban-Soporte-TI.pdf','CV-Juan-Esteban-Ofimatica.pdf','CV-Juan-Esteban-Desarrollo-ENG.pdf']) {
  assert(await exists('assets/cv/' + name), 'CV ausente: ' + name);
  assert((await readFile(path.join(root,'assets/cv',name))).subarray(0,5).toString() === '%PDF-', 'PDF inválido: ' + name);
}
const serialized = JSON.stringify(data).replace(/</g, '\\u003c');
const generated = '/* Generated by scripts/sync-data.mjs. */\nwindow.PORTFOLIO_DATA = ' + serialized + ';\n';
assert((await read('data/content.js')).replace(/\r\n/g, '\n') === generated, 'Ejecuta npm run sync: content.js no coincide con content.json.');

const html = await read('index.html');
const htmlIds = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]));
for (const match of html.matchAll(/\b(?:href|src)="([^"]+)"/g)) {
  const value = match[1];
  if (value.startsWith('#')) {
    assert(htmlIds.has(value.slice(1)), 'Ancla ausente: ' + value);
  } else if (!/^(https:|mailto:)/.test(value)) {
    assert(await exists(value), 'Recurso HTML ausente: ' + value);
  }
}
const cssFiles = ['css/style.css','assets/fonts/fonts.css'];
for (const relative of cssFiles) {
  for (const match of (await read(relative)).matchAll(/url\(\s*['"]?([^)'"]+)['"]?\s*\)/g)) {
    if (match[1].startsWith('#')) {
      assert(htmlIds.has(match[1].slice(1)), 'Referencia SVG ausente: ' + match[1]);
    } else if (!match[1].startsWith('data:')) {
      assert(await exists(path.join(path.dirname(relative), match[1])), 'Recurso CSS ausente: ' + match[1]);
    }
  }
}
for (const license of ['montserrat-OFL.txt','opensans-OFL.txt','robotomono-OFL.txt']) {
  assert(await exists('assets/fonts/' + license), 'Licencia ausente: ' + license);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exitCode = 1;
} else {
  console.log('OK: sintaxis, traducciones de datos, enlaces HTTPS, anclas y recursos locales.');
  console.log(data.projects.length + ' herramientas / ' + data.skills.length + ' áreas de conocimiento / ' + data.certifications.length + ' cursos y rutas.');
  console.log('Este control no verifica la disponibilidad de sitios externos.');
}
